// Writes the next account migration after an @royer/auth upgrade: applies the
// migrations already in migrations/ to an empty in-memory PostgreSQL, asks the
// installed package what its central adapter still needs, and writes only that
// difference. Nothing is applied to a real database and no issuer is contacted.
// Statements are idempotent, so a rerun never fails or drops data.
//
//   node scripts/plan-accounts-upgrade.mjs 0003_accounts_rc5
import { readFile, writeFile } from "node:fs/promises"
import { PGlite } from "@electric-sql/pglite"
import { PGLiteSocketServer } from "@electric-sql/pglite-socket"
import { createFederatedAuth } from "@royer/auth/federation"
import { getMigrations } from "better-auth/db/migration"
import pg from "pg"
import { readMigrations } from "./migrations.mjs"

const name = process.argv[2]
if (!/^\d{4}_[a-z0-9_]+$/.test(name ?? "")) throw new Error("Name the file, for example 0003_accounts_rc5.")
const { version } = JSON.parse(
  await readFile(new URL("../node_modules/@royer/auth/package.json", import.meta.url), "utf8")
)

const database = await PGlite.create()
const server = new PGLiteSocketServer({ db: database, host: "127.0.0.1", port: 0 })
await server.start()
const pool = new pg.Pool({
  connectionString: `postgresql://postgres@${server.getServerConn()}/postgres?sslmode=disable`,
  max: 1,
})
try {
  for (const migration of await readMigrations()) await pool.query(migration.sql)
  const auth = createFederatedAuth({
    appId: "devlinks",
    appName: "Devlinks",
    baseURL: "https://devlinks.example",
    secret: "migration-planning-only-secret-0123456789",
    database: pool,
    issuerURL: "https://issuer.example/api/auth",
    clientId: "migration-planning-only",
    clientSecret: "migration-planning-only",
  })
  const plan = await getMigrations(auth.engine.options)
  if (plan.unsafeChanges?.length || plan.schemaProblems?.length)
    throw new Error("The upgrade asks for a change that is not purely additive; review it by hand.")
  if (!plan.toBeAdded.length && !plan.toBeCreated.length) {
    console.log(JSON.stringify({ planned: false, reason: "nothing to add" }))
    process.exit(0)
  }
  const sql = (await plan.compileMigrations())
    .replaceAll(/^create table "/gm, 'create table if not exists "')
    .replaceAll(/ add column "/g, ' add column if not exists "')
    .replaceAll(
      /^create (unique )?index "/gm,
      (_match, unique) => `create ${unique ?? ""}index if not exists "`
    )
  const header =
    `-- Generated by scripts/plan-accounts-upgrade.mjs from @royer/auth ${version} (central mode),\n` +
    "-- on top of the earlier files in migrations/. Additive only.\n\n"
  await writeFile(new URL(`../migrations/${name}.sql`, import.meta.url), header + sql.trim() + "\n")
  console.log(
    JSON.stringify({
      planned: true,
      applied: false,
      version,
      added: plan.toBeAdded.map(({ table, fields }) => ({ table, fields: Object.keys(fields) })),
      created: plan.toBeCreated.map(({ table }) => table),
    })
  )
} finally {
  await pool.end()
  await server.stop()
  await database.close()
}
